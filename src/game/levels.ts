export function endlessGrid(level: number): Grid {
  const rows = Math.min(3 + Math.floor(level / 2), 7);
  const maxHits = Math.min(1 + Math.floor(level / 3), 3);
  const g: Grid = [];
  for (let r = 0; r < rows; r++) {
    const row: number[] = [];
    for (let c = 0; c < COLS; c++) {
      const rnd = Math.random();
      if (rnd < 0.12) row.push(0);
      else if (rnd > 0.96 && level > 4) row.push(4);
      else row.push(1 + Math.floor(Math.random() * maxHits));
    }
    g.push(row);
  }
  return g;
}

