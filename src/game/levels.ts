export const COLS = 10;

export type Grid = number[][]; // 0 = empty, 1..3 = hits, 4 = unbreakable

const P = (rows: string[]): Grid =>
  rows.map((r) =>
    r
      .padEnd(COLS, ".")
      .slice(0, COLS)
      .split("")
      .map((c) => (c === "." ? 0 : c === "#" ? 4 : Number(c))),
  );

